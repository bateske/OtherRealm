// Original 3x5 geometric font. Row bits are ordered left-to-right, MSB first.
#pragma once
#include <stdint.h>
namespace otherrealm {
inline uint8_t fontRow(uint8_t ch,uint8_t row){
    static const uint16_t glyphs[64]={
        0x0,0x2092,0x2d,0x5f7d,0x0,0x588d,0x3aaa,0x12,0x1491,0x4494,0xaa8,0x5d0,0x4400,0x1c0,0x2000,0x4889,0x7b6f,0x74b2,0x788e,0x628e,0x13ed,0x63a7,0x2ba3,0x248f,0x2aaa,0x62ea,0x410,0x4410,0x1511,0xe38,0x4454,0x208e,0x39ef,0x5bea,0x6bae,0x3923,0x6b6e,0x79a7,0x49a7,0x3b63,0x5bed,0x7497,0x2a49,0x5bad,0x7924,0x5bfd,0x5ffd,0x2b6a,0x49ae,0x176a,0x5bae,0x62a3,0x2497,0x7b6d,0x2b6d,0x5fed,0x5aad,0x24ad,0x788f,0x3493,0x0,0x6496,0x0,0x7000
    };
    if(ch>='a'&&ch<='z')ch-=32;
    if(ch=='|')return row<5?2:0;
    if(ch=='~')return row==1?3:row==2?6:0;
    if(ch<32||ch>95||row>4)return 0;
    return (glyphs[ch-32]>>(row*3))&7;
}
}
